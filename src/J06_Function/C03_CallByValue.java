package J06_Function;
import java.util.*;
public class C03_CallByValue {
    public static void main(String[] args){
        // swap - value exchang

        int a = 5;
        int b =10;

        //swap
       int temp=a;
       a=b;
       b=temp;

       System.out.println("a ="+a);
       System.out.println("b =" +b);




    }

}
